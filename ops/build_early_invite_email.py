"""Build the early adopter invite (Supabase edge function `early-invite`) from the house template (ops/lms_email.py).

    python3 ops/build_early_invite_email.py    # writes email.js and a preview in ops/out/early-invite.html

Any change goes to Amit as a preview first and is deployed only when he says "send".
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import lms_email as L  # noqa: E402

SIGN_IN = "https://myrobotisa.com/members/?src=early-invite"
OUT_JS = HERE / "supabase" / "functions" / "early-invite" / "email.js"
FOOT = ("You're getting this because Amit added you as an early adopter. Questions? Just reply to this email. "
        "It starts on practice money. Software and a course, not financial advice. Capital at risk.")
TICKS = ["Every lesson and video, the same as a paying member",
         "The QuickStart: your own robot on practice money, in about 30 minutes",
         "A free licence, so it's yours to keep using",
         "Your first year of Robot Care free, worth £120"]
ASK = ("You're trying this before anyone else, so some things will break, and that's the point. Tell me where you got "
       "stuck and anything that didn't make sense. Post it in the Moonshotters in the members area, or just reply to this email.")
HOW = "Sign in with this email address and we'll send you a code. Then open Set up my robot."


def build():
    blocks = [
        {"heading": "Does it need me?", "status": ("About 30 minutes", "green"), "accent": True, "prose": [HOW]},
        {"heading": "What you get", "ticks": TICKS},
        {"heading": "What I'd love from you", "prose": [ASK]},
        {"quote": {"text": "Thank you for trying it first.", "by": "Amit, founder", "img": L.MRI_LOGO}},
    ]
    html = L.render("You're in", "My Robot I.S.A.", "You're one of the first people to try it.", blocks, footnote=FOOT,
                    brand=L.MRI_BRAND, internal=False, label="Early adopter", mood=L.MOODS["milestone"],
                    hero={"accent": "early", "button": ("Sign in", SIGN_IN, True)})
    text = ("YOU'RE IN EARLY\nYou're one of the first people to try My Robot I.S.A.\n\n" + HOW + "\nSign in: " + SIGN_IN + "\n\n"
            "WHAT YOU GET\n" + "\n".join("- " + t for t in TICKS) + "\n\nWHAT I'D LOVE FROM YOU\n" + ASK +
            "\n\nThank you for trying it first.\nAmit, founder\n\n--\n" + FOOT)
    subject = L.subject("My Robot I.S.A.", "Account", "You're in early", internal=False)
    t = {"subject": subject, "html": html, "text": text}
    OUT_JS.write_text("// GENERATED by ops/build_early_invite_email.py from ops/lms_email.py. Do not edit by hand.\n"
                      f"const T = {json.dumps(t, ensure_ascii=False)};\n\nexport function buildInvite() {{ return T; }}\n", encoding="utf-8")
    out = HERE / "out"; out.mkdir(exist_ok=True)
    (out / "early-invite.html").write_text(html, encoding="utf-8")
    print(subject)


if __name__ == "__main__":
    build()
