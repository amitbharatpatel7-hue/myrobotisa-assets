// waitlist-welcome: sends the one-off welcome email to new My Robot I.S.A. sign-ups.
//
// Called with no auth (verify_jwt off) by:
//   - the AFTER INSERT trigger on public.waitlist (body {"id": <new row id>}), within seconds of sign-up
//   - the AFTER UPDATE trigger when a welcome becomes due again (newsletter-only joins the test drive,
//     or someone re-joins after unsubscribing)
//   - a pg_cron backstop every 15 minutes (no body), only when something is still pending
// It can only ever email rows that signed up through the form and have not been welcomed, each once,
// so calling it from outside sends nothing new. Secrets: RESEND_API_KEY (set by Amit in Supabase).
// Source of record since 1 Nov 2026 (copied from deployed v29); email.js is generated by ops/build_welcome_email.py.
import { buildWelcome } from "./email.js";

const URL_ = Deno.env.get("SUPABASE_URL")!;
const SRK = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
const RESEND = Deno.env.get("RESEND_API_KEY");
const FROM = "My Robot I.S.A. <hello@myrobotisa.com>";
const WELCOME_FROM = "2026-10-16T00:00:00Z"; // rows before this (tests) are never emailed
const WINDOW_DAYS = 3;                         // don't send a "welcome" that became due days ago
const UNSUB_PAGE = "https://myrobotisa.com/unsubscribe/";
const UNSUB_API = `${URL_}/functions/v1/waitlist-unsubscribe`;

const db = (path: string, init: RequestInit = {}) =>
  fetch(`${URL_}/rest/v1/${path}`, {
    ...init,
    headers: { apikey: SRK, Authorization: `Bearer ${SRK}`, "Content-Type": "application/json", ...(init.headers || {}) },
  });

const json = (status: number, body: unknown) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });

Deno.serve(async (req) => {
  if (req.method !== "POST") return json(405, { error: "POST only" });
  if (!RESEND) return json(503, { error: "RESEND_API_KEY not set; nothing sent" });

  // Never send an email whose unsubscribe link would be broken.
  const page = await fetch(UNSUB_PAGE, { method: "HEAD" }).catch(() => null);
  if (!page || !page.ok) return json(503, { error: "unsubscribe page not live yet; nothing sent" });

  let id: number | null = null;
  try { const b = await req.json(); if (Number.isInteger(b?.id)) id = b.id; } catch { /* backstop call: no body */ }

  const since = new Date(Math.max(Date.parse(WELCOME_FROM), Date.now() - WINDOW_DAYS * 864e5)).toISOString();
  const q = `waitlist?select=id&welcomed_at=is.null&unsubscribed_at=is.null&welcome_due_at=gte.${encodeURIComponent(since)}` +
    (id !== null ? `&id=eq.${id}` : "") + "&order=id.asc&limit=20";
  const pending = await db(q);
  if (!pending.ok) return json(500, { error: "lookup failed", status: pending.status });
  const ids: { id: number }[] = await pending.json();

  const results: unknown[] = [];
  for (const { id: rid } of ids) {
    // Claim the row first, so the triggers and the backstop can never both send.
    const claim = await db(`waitlist?id=eq.${rid}&welcomed_at=is.null&select=id,email,launch_list,newsletter,unsub_token,welcome_due_at`, {
      method: "PATCH", headers: { Prefer: "return=representation" }, body: JSON.stringify({ welcomed_at: new Date().toISOString() }),
    });
    const rows = claim.ok ? await claim.json() : [];
    if (!rows.length) { results.push({ id: rid, skipped: "already claimed" }); continue; }
    const row = rows[0];

    const unsubUrl = `${UNSUB_PAGE}?t=${row.unsub_token}`;
    const { subject, html, text } = buildWelcome(row, unsubUrl);
    const sent = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${RESEND}`, "Content-Type": "application/json", "Idempotency-Key": `waitlist-welcome-${rid}-${Date.parse(row.welcome_due_at) || 0}` },
      body: JSON.stringify({
        from: FROM, to: [row.email], reply_to: "hello@myrobotisa.com", subject, html, text,
        headers: { "List-Unsubscribe": `<${UNSUB_API}?t=${row.unsub_token}>`, "List-Unsubscribe-Post": "List-Unsubscribe=One-Click" },
        tags: [{ name: "kind", value: "waitlist_welcome" }],
      }),
    });
    if (sent.ok) {
      results.push({ id: rid, sent: true });
    } else {
      // Release the claim so the backstop retries later.
      await db(`waitlist?id=eq.${rid}`, { method: "PATCH", body: JSON.stringify({ welcomed_at: null }) });
      results.push({ id: rid, sent: false, status: sent.status });
    }
  }
  return json(200, { checked: ids.length, results });
});
