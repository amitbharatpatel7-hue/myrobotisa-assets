"""Builds ask_email.js: the email Robot Care sends Amit when it can't answer a member's question about a fix.

The edge function runs in Deno and can't import ops/lms_email.py, so the HTML is rendered once here by lms_email (the
single source of truth for email HTML) with {{placeholders}}, and ask_email.js fills them in, HTML-escaped. Re-run after
any change to lms_email.py:  python3 ops/supabase/functions/robot-care/build_ask_email.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2]))
import lms_email as E  # noqa: E402

SUBJECT = E.subject("My Robot I.S.A.", "Support", "A member asked about a Robot Care fix")
html = E.render(
    title="A member's question needs you",
    eyebrow_text="Robot Care question",
    subtitle="Robot Care couldn't answer it from the fix, so it's yours. One email per question.",
    brand=E.MRI_BRAND, badge="Support", mood=False,
    blocks=[
        {"heading": "The question", "status": ("Needs you", "amber"), "accent": True, "prose": ["{{question}}"]},
        {"heading": "The fix", "status": ("{{state}}", "muted"),
         "kv": [("Member", "{{member}}"), ("Copy", "{{repo}}"), ("Fix", "{{title}}"), ("What went wrong", "{{diagnosis}}")]},
    ],
    buttons=[("Open the fix on GitHub", "{{pr}}", True)],
    footnote="Reply to the member by email, or post a Message in the members area. Their question is also logged in robot_care_requests.",
)
text = ("A member's question about a Robot Care fix needs you.\n\nQuestion: {{question}}\n\nMember: {{member}}\nCopy: {{repo}}\n"
        "Fix: {{title}} ({{state}})\nWhat went wrong: {{diagnosis}}\nOpen it: {{pr}}\n\n"
        "Reply to the member by email, or post a Message in the members area.")
out = ("// GENERATED by build_ask_email.py from ops/lms_email.py. Do not edit by hand.\n"
       f"export const SUBJECT = {json.dumps(SUBJECT)};\n"
       f"export const HTML = {json.dumps(html)};\n"
       f"export const TEXT = {json.dumps(text)};\n"
       "const esc = (s) => String(s ?? \"\").replace(/[&<>\"']/g, (c) => ({ \"&\": \"&amp;\", \"<\": \"&lt;\", \">\": \"&gt;\", '\"': \"&quot;\", \"'\": \"&#39;\" })[c]);\n"
       "export function fill(v) {\n"
       "  const sub = (t, f) => t.replace(/\\{\\{(\\w+)\\}\\}/g, (_, k) => f(k in v ? v[k] : \"\"));\n"
       "  return { subject: SUBJECT, html: sub(HTML, esc), text: sub(TEXT, (s) => String(s ?? \"\")) };\n"
       "}\n")
(HERE / "ask_email.js").write_text(out)
print("wrote ask_email.js", len(out), "bytes")
